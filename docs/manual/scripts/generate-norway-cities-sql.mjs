#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const YEAR='2026';
const MIN_POPULATION=5000;
const SSB_API='https://data.ssb.no/api/v0/en/table';
const PLACE_API='https://ws.geonorge.no/stedsnavn/v1/navn';
const currentCountyNames={
  '03':'Oslo','11':'Rogaland','15':'Møre og Romsdal','18':'Nordland',
  '31':'Østfold','32':'Akershus','33':'Buskerud','34':'Innlandet',
  '39':'Vestfold','40':'Telemark','42':'Agder','46':'Vestland',
  '50':'Trøndelag','55':'Troms','56':'Finnmark'
};

async function getJson(url,options={}){
  let lastError;
  for(let attempt=1;attempt<=4;attempt++){
    try{
      const response=await fetch(url,{...options,headers:{Accept:'application/json','Content-Type':'application/json',...(options.headers||{})}});
      if(!response.ok)throw new Error(`${response.status} ${response.statusText}: ${await response.text()}`);
      return await response.json();
    }catch(error){lastError=error;if(attempt<4)await new Promise(resolve=>setTimeout(resolve,attempt*500));}
  }
  throw lastError;
}

async function statbank(table,query){
  return getJson(`${SSB_API}/${table}`,{method:'POST',body:JSON.stringify({query,response:{format:'json-stat2'}})});
}

function dimensionCodes(dataset,code){
  const category=dataset.dimension[code].category;
  if(Array.isArray(category.index))return category.index;
  return Object.entries(category.index).sort((a,b)=>a[1]-b[1]).map(([value])=>value);
}

function dimensionLabels(dataset,code){
  const category=dataset.dimension[code].category;
  return dimensionCodes(dataset,code).map(value=>category.label?.[value]??value);
}

function itemSelection(code,values){return{code,selection:{filter:'item',values}};}

function normalize(value){
  return String(value||'').normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/[^a-z0-9]/g,'');
}

function scorePlace(hit,targetName){
  const type=String(hit.navneobjekttype||'').toLowerCase();
  const preferredTypes=['by','tettsted','bydel','tettbebyggelse','bebyggelse','grend'];
  let score=normalize(hit.skrivemåte)===normalize(targetName)?100:0;
  const typeIndex=preferredTypes.indexOf(type);
  if(typeIndex>=0)score+=30-typeIndex*3;
  if(hit.navnestatus==='hovednavn')score+=10;
  if(String(hit.skrivemåtestatus||'').includes('prioritert'))score+=8;
  if(hit.stedstatus==='aktiv')score+=5;
  return score;
}

async function lookupCoordinate(city){
  const rawNames=[city.name,city.name.split('/')[0],city.name.replace(/\s*\([^)]*\)\s*/g,'').trim(),city.municipalityName];
  const names=[...new Set(rawNames.filter(Boolean))];
  for(const searchName of names){
    const params=new URLSearchParams({knr:city.municipalityCode,sok:searchName,utkoordsys:'4258',treffPerSide:'100',side:'1'});
    const result=await getJson(`${PLACE_API}?${params}`);
    const candidates=(result.navn||[]).filter(hit=>Number.isFinite(Number(hit.representasjonspunkt?.nord))&&Number.isFinite(Number(hit.representasjonspunkt?.øst)));
    if(candidates.length){
      candidates.sort((a,b)=>scorePlace(b,searchName)-scorePlace(a,searchName));
      const point=candidates[0].representasjonspunkt;
      return{latitude:Number(point.nord),longitude:Number(point.øst),coordinateName:candidates[0].skrivemåte,coordinateType:candidates[0].navneobjekttype};
    }
  }
  throw new Error(`No Kartverket coordinate found for ${city.name} (${city.municipalityCode} ${city.municipalityName})`);
}

async function mapConcurrent(items,limit,mapper){
  const results=new Array(items.length);let cursor=0;
  async function worker(){while(true){const index=cursor++;if(index>=items.length)return;results[index]=await mapper(items[index],index);}}
  await Promise.all(Array.from({length:Math.min(limit,items.length)},worker));
  return results;
}

function sqlString(value){return `N'${String(value).replaceAll("'","''")}'`;}
function sqlDecimal(value){return Number(value).toFixed(6);}

function renderSql(cities){
  const lines=[
    '-- Norwegian urban settlements with more than 5,000 residents.',
    `-- Population: Statistics Norway (SSB), table 04859/14216, ${YEAR}.`,
    '-- Coordinates: Kartverket official Place Name API, ETRS89/WGS84 (EPSG:4258).',
    '-- Generated by documentation/scripts/generate-norway-cities-sql.mjs.',
    '',
    'SET NOCOUNT ON;',
    'SET XACT_ABORT ON;',
    'BEGIN TRANSACTION;',
    '',
    "IF OBJECT_ID(N'dbo.NorwayCity', N'U') IS NULL",
    'BEGIN',
    '    CREATE TABLE dbo.NorwayCity',
    '    (',
    '        CityId                    int IDENTITY(1,1) NOT NULL CONSTRAINT PK_NorwayCity PRIMARY KEY,',
    '        SsbUrbanSettlementCode    char(4) NOT NULL,',
    '        Name                      nvarchar(200) NOT NULL,',
    '        MunicipalityCode          char(4) NOT NULL,',
    '        MunicipalityName          nvarchar(200) NOT NULL,',
    '        CountyCode                char(2) NOT NULL,',
    '        CountyName                nvarchar(100) NOT NULL,',
    '        Population                int NOT NULL,',
    '        PopulationYear            smallint NOT NULL,',
    '        Latitude                  decimal(9,6) NOT NULL,',
    '        Longitude                 decimal(9,6) NOT NULL,',
    '        CoordinateSource          nvarchar(100) NOT NULL CONSTRAINT DF_NorwayCity_CoordinateSource DEFAULT N\'Kartverket SSR\',',
    '        UpdatedAtUtc              datetime2(0) NOT NULL CONSTRAINT DF_NorwayCity_UpdatedAtUtc DEFAULT SYSUTCDATETIME(),',
    '        CONSTRAINT UQ_NorwayCity_SsbCodeYear UNIQUE (SsbUrbanSettlementCode, PopulationYear),',
    '        CONSTRAINT CK_NorwayCity_Population CHECK (Population >= 0),',
    '        CONSTRAINT CK_NorwayCity_Latitude CHECK (Latitude BETWEEN 57 AND 72),',
    '        CONSTRAINT CK_NorwayCity_Longitude CHECK (Longitude BETWEEN 4 AND 32)',
    '    );',
    'END;',
    '',
    `DELETE FROM dbo.NorwayCity WHERE PopulationYear = ${YEAR};`,
    ''
  ];
  for(const city of cities){
    lines.push(
      'INSERT INTO dbo.NorwayCity',
      '    (SsbUrbanSettlementCode, Name, MunicipalityCode, MunicipalityName, CountyCode, CountyName, Population, PopulationYear, Latitude, Longitude)',
      `VALUES ('${city.code}', ${sqlString(city.name)}, '${city.municipalityCode}', ${sqlString(city.municipalityName)}, '${city.countyCode}', ${sqlString(city.countyName)}, ${city.population}, ${YEAR}, ${sqlDecimal(city.latitude)}, ${sqlDecimal(city.longitude)});`,
      ''
    );
  }
  lines.push('COMMIT TRANSACTION;','',`SELECT * FROM dbo.NorwayCity WHERE PopulationYear = ${YEAR} ORDER BY Population DESC, Name;`,'');
  return lines.join('\n');
}

function renderExistingCitySql(cities){
  const populationAsOfDate=`${YEAR}-01-01`;
  const dataSource='SSB 04859 / Kartverket SSR';
  const lines=[
    '-- Upserts Norwegian urban settlements with more than 5,000 residents into dbo.City.',
    `-- Population as of ${populationAsOfDate}: Statistics Norway (SSB), table 04859/14216.`,
    '-- Coordinates: Kartverket official Place Name API, ETRS89/WGS84 (EPSG:4258).',
    '-- ExternalCode contains the SSB urban-settlement code prefixed with SSB:TETTSTED:.',
    '-- CityId is assumed to be an IDENTITY column and is intentionally omitted.',
    '-- Generated by documentation/scripts/generate-norway-cities-sql.mjs.',
    '',
    'SET NOCOUNT ON;',
    'SET XACT_ABORT ON;',
    '',
    "IF OBJECT_ID(N'dbo.City', N'U') IS NULL",
    "    THROW 50001, 'The required table dbo.City does not exist.', 1;",
    '',
    'BEGIN TRANSACTION;',
    ''
  ];
  for(const city of cities){
    const externalCode=`SSB:TETTSTED:${city.code}`;
    lines.push(
      `UPDATE dbo.City`,
      `SET CityName = ${sqlString(city.name)},`,
      `    MunicipalityName = ${sqlString(city.municipalityName)},`,
      `    CountyName = ${sqlString(city.countyName)},`,
      `    Population = ${city.population},`,
      `    PopulationAsOfDate = CONVERT(date, '${populationAsOfDate}'),`,
      `    Latitude = ${sqlDecimal(city.latitude)},`,
      `    Longitude = ${sqlDecimal(city.longitude)},`,
      `    CountryCode = 'NO',`,
      `    DataSource = ${sqlString(dataSource)},`,
      `    UpdatedUtc = SYSUTCDATETIME()`,
      `WHERE ExternalCode = ${sqlString(externalCode)};`,
      '',
      'IF @@ROWCOUNT = 0',
      'BEGIN',
      '    INSERT INTO dbo.City',
      '        (CityName, MunicipalityName, CountyName, ExternalCode, Population, PopulationAsOfDate, Latitude, Longitude, CountryCode, DataSource, CreatedUtc, UpdatedUtc)',
      `    VALUES (${sqlString(city.name)}, ${sqlString(city.municipalityName)}, ${sqlString(city.countyName)}, ${sqlString(externalCode)}, ${city.population}, CONVERT(date, '${populationAsOfDate}'), ${sqlDecimal(city.latitude)}, ${sqlDecimal(city.longitude)}, 'NO', ${sqlString(dataSource)}, SYSUTCDATETIME(), SYSUTCDATETIME());`,
      'END;',
      ''
    );
  }
  lines.push('COMMIT TRANSACTION;','','SELECT CityId, CityName, MunicipalityName, CountyName, ExternalCode, Population, PopulationAsOfDate, Latitude, Longitude, CountryCode, DataSource, CreatedUtc, UpdatedUtc','FROM dbo.City',`WHERE DataSource = ${sqlString(dataSource)}`,'ORDER BY Population DESC, CityName;','');
  return lines.join('\n');
}

async function main(){
  const populationData=await statbank('04859',[
    {code:'TettSted',selection:{filter:'all',values:['*']}},
    itemSelection('ContentsCode',['Bosatte']),
    itemSelection('Tid',[YEAR])
  ]);
  const settlementCodes=dimensionCodes(populationData,'TettSted');
  const settlementNames=dimensionLabels(populationData,'TettSted');
  const selected=settlementCodes.map((code,index)=>({code,name:settlementNames[index],population:Number(populationData.value[index])}))
    .filter(city=>city.code!=='9999'&&Number.isFinite(city.population)&&city.population>MIN_POPULATION);

  const relationMeta=await getJson(`${SSB_API}/14216`);
  const regionVariable=relationMeta.variables.find(variable=>variable.code==='Region');
  const currentRegions=regionVariable.values.map((code,index)=>({code,name:regionVariable.valueTexts[index]}))
    .filter(region=>currentCountyNames[region.code.slice(0,2)]);
  const regionNameByCode=new Map(currentRegions.map(region=>[region.code,region.name]));

  const allocationData=await statbank('14216',[
    itemSelection('Region',currentRegions.map(region=>region.code)),
    itemSelection('TettSted',selected.map(city=>city.code)),
    itemSelection('ContentsCode',['Bosatte']),
    itemSelection('Tid',[YEAR])
  ]);
  const allocationRegions=dimensionCodes(allocationData,'Region');
  const allocationSettlements=dimensionCodes(allocationData,'TettSted');
  const settlementCount=allocationSettlements.length;
  const primaryRegionBySettlement=new Map();
  allocationRegions.forEach((regionCode,regionIndex)=>allocationSettlements.forEach((settlementCode,settlementIndex)=>{
    const population=Number(allocationData.value[regionIndex*settlementCount+settlementIndex]);
    const current=primaryRegionBySettlement.get(settlementCode);
    if(Number.isFinite(population)&&(!current||population>current.population))primaryRegionBySettlement.set(settlementCode,{regionCode,population});
  }));

  const cities=selected.map(city=>{
    const primary=primaryRegionBySettlement.get(city.code);
    if(!primary)throw new Error(`No current municipality allocation found for ${city.code} ${city.name}`);
    const countyCode=primary.regionCode.slice(0,2);
    return{...city,municipalityCode:primary.regionCode,municipalityName:regionNameByCode.get(primary.regionCode),countyCode,countyName:currentCountyNames[countyCode]};
  });

  const geocoded=await mapConcurrent(cities,6,async(city,index)=>{
    const coordinate=await lookupCoordinate(city);
    process.stdout.write(`\rGeocoded ${index+1}/${cities.length}: ${city.name}                    `);
    return{...city,...coordinate};
  });
  process.stdout.write('\n');
  geocoded.sort((a,b)=>b.population-a.population||a.name.localeCompare(b.name,'nb'));

  for(const city of geocoded){
    if(city.latitude<57||city.latitude>72||city.longitude<4||city.longitude>32)throw new Error(`Coordinate outside Norway bounds: ${city.name} ${city.latitude},${city.longitude}`);
  }

  const scriptDir=path.dirname(fileURLToPath(import.meta.url));
  const outputPath=path.resolve(scriptDir,'../sql/norway-cities-over-5000.sql');
  const existingTableOutputPath=path.resolve(scriptDir,'../sql/norway-cities-over-5000-insert-dbo-city.sql');
  await fs.mkdir(path.dirname(outputPath),{recursive:true});
  await fs.writeFile(outputPath,renderSql(geocoded),'utf8');
  await fs.writeFile(existingTableOutputPath,renderExistingCitySql(geocoded),'utf8');
  console.log(`Wrote ${geocoded.length} cities to ${outputPath}`);
  console.log(`Wrote dbo.City upsert script to ${existingTableOutputPath}`);
}

main().catch(error=>{console.error(error);process.exitCode=1;});
